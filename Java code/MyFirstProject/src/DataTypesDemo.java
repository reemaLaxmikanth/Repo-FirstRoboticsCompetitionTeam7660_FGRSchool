public class DataTypesDemo {
    public static void demonstrate() {
        int a = 7;
        int b = 5;
        int intSum = a + b;

        float x = 3.5f;
        float y = 2.2f;
        float floatSum = x + y;

        System.out.println("Integer addition: " + a + " + " + b + " = " + intSum);
        System.out.println("Float addition: " + x + " + " + y + " = " + floatSum);
    }
}
